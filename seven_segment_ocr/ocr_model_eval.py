"""Unified evaluation for seven-segment OCR model candidates.

The common contract is a JSON result schema. ONNX Runtime is used for models
that are available as faithful ONNX graphs. Closed SDK models, such as ML Kit,
are imported as black-box prediction files generated by their official runtime.
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

import numpy as np
from PIL import Image, ImageOps


CHARSET = "0123456789/. -\n"
SCHEMA_VERSION = 1


@dataclass(frozen=True)
class LabeledSample:
    image_path: Path
    label: str

    @property
    def filename(self) -> str:
        return self.image_path.name


def normalize_text(text: str) -> str:
    return " ".join(str(text).strip().split())


def levenshtein(a: str, b: str) -> int:
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, start=1):
        cur = [i]
        for j, cb in enumerate(b, start=1):
            cost = 0 if ca == cb else 1
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost))
        prev = cur
    return prev[-1]


def summarize_text_metrics(pairs: Iterable[tuple[str, str]]) -> dict[str, float]:
    rows = list(pairs)
    if not rows:
        return {
            "exact": 0.0,
            "normalized_exact": 0.0,
            "cer": 0.0,
            "digit_accuracy": 0.0,
        }

    exact = 0
    normalized_exact = 0
    edit_total = 0
    char_total = 0
    digit_errors = 0
    digit_total = 0
    for truth, pred in rows:
        truth = str(truth)
        pred = str(pred)
        if pred == truth:
            exact += 1
        if normalize_text(pred) == normalize_text(truth):
            normalized_exact += 1
        edit_total += levenshtein(truth, pred)
        char_total += max(1, len(truth))

        truth_digits = "".join(ch for ch in truth if ch.isdigit())
        pred_digits = "".join(ch for ch in pred if ch.isdigit())
        denom = max(len(truth_digits), len(pred_digits), 1)
        digit_errors += levenshtein(truth_digits, pred_digits)
        digit_total += denom

    return {
        "exact": exact / len(rows),
        "normalized_exact": normalized_exact / len(rows),
        "cer": edit_total / char_total,
        "digit_accuracy": max(0.0, 1.0 - (digit_errors / digit_total)),
    }


def summarize_latencies(latencies_ms: Iterable[float | None]) -> dict[str, float | None]:
    values = sorted(float(v) for v in latencies_ms if v is not None)
    if not values:
        return {"mean": None, "p50": None, "p95": None, "min": None, "max": None}
    p95_index = min(len(values) - 1, int(round((len(values) - 1) * 0.95)))
    return {
        "mean": statistics.fmean(values),
        "p50": statistics.median(values),
        "p95": values[p95_index],
        "min": values[0],
        "max": values[-1],
    }


def load_labeled_dataset(dataset_dir: str | Path) -> list[LabeledSample]:
    root = Path(dataset_dir)
    csv_path = root / "sequences.csv"
    if not csv_path.exists():
        csv_path = root / "labels.csv"
    if not csv_path.exists():
        raise FileNotFoundError(f"expected sequences.csv or labels.csv in {root}")

    samples: list[LabeledSample] = []
    with csv_path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or "filename" not in reader.fieldnames:
            raise ValueError(f"{csv_path} must include a filename column")
        label_column = "label" if "label" in reader.fieldnames else "text"
        if label_column not in reader.fieldnames:
            raise ValueError(f"{csv_path} must include a label or text column")
        for row in reader:
            filename = row["filename"]
            image_path = root / filename
            if not image_path.exists():
                image_path = root / "images" / filename
            if not image_path.exists():
                raise FileNotFoundError(f"image listed in {csv_path} not found: {filename}")
            samples.append(LabeledSample(image_path=image_path, label=row[label_column]))
    return samples


def measure_model_file(model_path: str | Path) -> dict[str, int | str | None]:
    path = Path(model_path)
    info: dict[str, int | str | None] = {
        "format": path.suffix.lstrip(".").lower() or "unknown",
        "model_bytes": path.stat().st_size,
        "parameter_count": None,
    }
    if path.suffix.lower() == ".onnx":
        import onnx

        model = onnx.load(str(path), load_external_data=False)
        count = 0
        for initializer in model.graph.initializer:
            dims = [int(dim) for dim in initializer.dims]
            count += int(np.prod(dims)) if dims else 1
        info["parameter_count"] = count
    return info


def _preprocess_for_onnx(image_path: Path, input_shape: list[object]) -> np.ndarray:
    height = _shape_dim(input_shape, 2, 128)
    width = _shape_dim(input_shape, 3, 256)
    gray = ImageOps.exif_transpose(Image.open(image_path)).convert("L")
    ratio = height / max(1, gray.height)
    new_width = max(1, min(width, int(round(gray.width * ratio))))
    gray = gray.resize((new_width, height), Image.Resampling.LANCZOS)
    padded = Image.new("L", (width, height), 0)
    padded.paste(gray, (0, 0))
    arr = np.asarray(padded, dtype=np.float32) / 255.0
    return arr.reshape(1, 1, height, width)


def _shape_dim(shape: list[object], index: int, default: int) -> int:
    try:
        value = shape[index]
    except IndexError:
        return default
    return int(value) if isinstance(value, int) and value > 0 else default


def ctc_decode(logits: np.ndarray, charset: str = CHARSET) -> str:
    if logits.ndim == 3:
        if logits.shape[0] == 1:
            logits = logits[0]
        elif logits.shape[1] == 1:
            logits = logits[:, 0, :]
        else:
            logits = logits[0]
    if logits.ndim != 2:
        raise ValueError(f"expected 2D or 3D CTC logits, got shape {logits.shape}")
    indices = np.argmax(logits, axis=1)
    chars: list[str] = []
    prev = -1
    for raw_idx in indices:
        idx = int(raw_idx)
        if idx != 0 and idx != prev:
            char_idx = idx - 1
            if 0 <= char_idx < len(charset):
                chars.append(charset[char_idx])
        prev = idx
    return postprocess_ctc("".join(chars))


def postprocess_ctc(text: str) -> str:
    text = normalize_text(text)
    while "//" in text or ".." in text or "--" in text:
        text = text.replace("//", "/").replace("..", ".").replace("--", "-")
    return text.strip("/.- ")


def evaluate_onnx_model(
    model_id: str,
    model_path: str | Path,
    samples: list[LabeledSample],
    *,
    limit: int | None = None,
    warmup: int = 2,
    providers: list[str] | None = None,
) -> dict[str, object]:
    import onnxruntime as ort

    selected = samples[:limit] if limit else samples
    session = ort.InferenceSession(
        str(model_path),
        providers=providers or ["CPUExecutionProvider"],
    )
    input_meta = session.get_inputs()[0]
    input_name = input_meta.name
    input_shape = list(input_meta.shape)

    for sample in selected[:warmup]:
        tensor = _preprocess_for_onnx(sample.image_path, input_shape)
        session.run(None, {input_name: tensor})

    rows = []
    for sample in selected:
        tensor = _preprocess_for_onnx(sample.image_path, input_shape)
        start = time.perf_counter()
        outputs = session.run(None, {input_name: tensor})
        latency_ms = (time.perf_counter() - start) * 1000.0
        prediction = ctc_decode(np.asarray(outputs[0]))
        rows.append(
            {
                "filename": sample.filename,
                "truth": sample.label,
                "prediction": prediction,
                "latency_ms": latency_ms,
            }
        )

    return _build_model_result(
        model_id=model_id,
        backend="onnxruntime",
        capacity=measure_model_file(model_path),
        rows=rows,
    )


def evaluate_imported_predictions(
    samples: list[LabeledSample],
    predictions_path: str | Path,
) -> dict[str, object]:
    payload = json.loads(Path(predictions_path).read_text(encoding="utf-8"))
    raw_predictions = payload.get("predictions", {})
    if isinstance(raw_predictions, dict):
        prediction_by_name = {
            str(name): {"text": value, "latency_ms": None}
            for name, value in raw_predictions.items()
        }
    else:
        prediction_by_name = {
            str(row["filename"]): {
                "text": row.get("text", row.get("prediction", "")),
                "latency_ms": row.get("latency_ms"),
            }
            for row in raw_predictions
        }

    rows = []
    for sample in samples:
        pred = prediction_by_name.get(sample.filename, {"text": "", "latency_ms": None})
        rows.append(
            {
                "filename": sample.filename,
                "truth": sample.label,
                "prediction": str(pred.get("text", "")),
                "latency_ms": pred.get("latency_ms"),
            }
        )

    capacity = {
        "format": payload.get("format", "imported_predictions"),
        "model_bytes": payload.get("model_bytes"),
        "parameter_count": payload.get("parameter_count"),
    }
    return _build_model_result(
        model_id=str(payload.get("model_id", Path(predictions_path).stem)),
        backend=str(payload.get("backend", "imported")),
        capacity=capacity,
        rows=rows,
    )


def _build_model_result(
    *,
    model_id: str,
    backend: str,
    capacity: dict[str, object],
    rows: list[dict[str, object]],
) -> dict[str, object]:
    pairs = [(str(row["truth"]), str(row["prediction"])) for row in rows]
    return {
        "model_id": model_id,
        "backend": backend,
        "capacity": capacity,
        "latency_ms": summarize_latencies(row.get("latency_ms") for row in rows),
        "metrics": summarize_text_metrics(pairs),
        "samples": rows,
    }


def _build_error_result(model_id: str, backend: str, error: Exception) -> dict[str, object]:
    return {
        "model_id": model_id,
        "backend": backend,
        "status": "error",
        "error": {
            "type": type(error).__name__,
            "message": str(error),
        },
        "capacity": {},
        "latency_ms": summarize_latencies([]),
        "metrics": summarize_text_metrics([]),
        "samples": [],
    }


def format_results_table(results: list[dict[str, object]]) -> str:
    headers = [
        "model",
        "backend",
        "status",
        "size",
        "params",
        "mean",
        "p95",
        "exact",
        "cer",
        "digit",
    ]
    rows = [headers]
    for result in results:
        capacity = result.get("capacity", {})
        latency = result.get("latency_ms", {})
        metrics = result.get("metrics", {})
        status = str(result.get("status", "ok"))
        if status == "error":
            status = "ERROR"
        rows.append(
            [
                str(result.get("model_id", "")),
                str(result.get("backend", "")),
                status,
                _format_bytes(_mapping_get(capacity, "model_bytes")),
                _format_int(_mapping_get(capacity, "parameter_count")),
                _format_ms(_mapping_get(latency, "mean")),
                _format_ms(_mapping_get(latency, "p95")),
                _format_percent(_mapping_get(metrics, "exact")),
                _format_percent(_mapping_get(metrics, "cer")),
                _format_percent(_mapping_get(metrics, "digit_accuracy")),
            ]
        )
    widths = [max(len(row[i]) for row in rows) for i in range(len(headers))]
    lines = []
    for index, row in enumerate(rows):
        lines.append(" | ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)))
        if index == 0:
            lines.append(" | ".join("-" * width for width in widths))
    return "\n".join(lines)


def _mapping_get(value: object, key: str) -> object:
    return value.get(key) if isinstance(value, dict) else None


def _format_bytes(value: object) -> str:
    if value is None:
        return "n/a"
    number = float(value)
    if number >= 1024 * 1024:
        return f"{number / (1024 * 1024):.2f} MB"
    if number >= 1024:
        return f"{number / 1024:.2f} KB"
    return f"{int(number)} B"


def _format_int(value: object) -> str:
    return "n/a" if value is None else f"{int(value):,}"


def _format_ms(value: object) -> str:
    return "n/a" if value is None else f"{float(value):.2f} ms"


def _format_percent(value: object) -> str:
    return "n/a" if value is None else f"{float(value) * 100:.2f}%"


def _parse_model_spec(spec: str) -> tuple[str, Path]:
    if ":" not in spec:
        path = Path(spec)
        return path.stem, path
    model_id, path = spec.split(":", 1)
    return model_id, Path(path)


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", required=True, help="Directory with sequences.csv/labels.csv")
    parser.add_argument("--output", required=True, help="Output JSON path")
    parser.add_argument(
        "--onnx-model",
        action="append",
        default=[],
        metavar="ID:PATH",
        help="Evaluate an ONNX model. Can be repeated.",
    )
    parser.add_argument(
        "--import-predictions",
        action="append",
        default=[],
        metavar="PATH",
        help="Import black-box predictions JSON. Can be repeated.",
    )
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--warmup", type=int, default=2)
    parser.add_argument("--table-output", default=None, help="Optional plain text summary table path")
    parser.add_argument("--print-table", action="store_true", help="Print the summary table to stdout")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    samples = load_labeled_dataset(args.dataset)
    results: list[dict[str, object]] = []

    for spec in args.onnx_model:
        model_id, model_path = _parse_model_spec(spec)
        try:
            results.append(
                evaluate_onnx_model(
                    model_id,
                    model_path,
                    samples,
                    limit=args.limit,
                    warmup=args.warmup,
                )
            )
        except Exception as exc:
            results.append(_build_error_result(model_id, "onnxruntime", exc))

    selected_samples = samples[: args.limit] if args.limit else samples
    for predictions_path in args.import_predictions:
        results.append(evaluate_imported_predictions(selected_samples, predictions_path))

    payload = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "dataset": {
            "path": str(Path(args.dataset).resolve()),
            "sample_count": len(selected_samples),
        },
        "results": results,
    }
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    table = format_results_table(results)
    if args.table_output:
        Path(args.table_output).write_text(table + "\n", encoding="utf-8")
    if args.print_table:
        print(table)
    print(json.dumps({"output": str(output_path), "models": len(results)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
